--1A
CREATE TABLE S6_LRS (
    GEOM SDO_GEOMETRY
);

--1B
INSERT INTO S6_LRS
SELECT s.GEOM
FROM STREETS_AND_RAILROADS s, MAJOR_CITIES c
WHERE c.CITY_NAME = 'Koszalin'
  AND SDO_WITHIN_DISTANCE(s.GEOM, c.GEOM, 'distance=10 unit=km') = 'TRUE';

--1C
SELECT 
    SDO_GEOM.SDO_LENGTH(s.GEOM, 1, 'unit=km') AS DISTANCE,
    ST_LINESTRING(s.GEOM).ST_NUMPOINTS() AS ST_NUMPOINTS
FROM S6_LRS s;

--1D
UPDATE S6_LRS
SET GEOM = SDO_LRS.CONVERT_TO_LRS_GEOM(GEOM, 0, 276.6813154);

--1E
INSERT INTO USER_SDO_GEOM_METADATA (TABLE_NAME, COLUMN_NAME, DIMINFO, SRID)
VALUES (
    'S6_LRS',
    'GEOM',
    MDSYS.SDO_DIM_ARRAY(
        MDSYS.SDO_DIM_ELEMENT('X', 12.0, 24.0, 1),
        MDSYS.SDO_DIM_ELEMENT('Y', 48.0, 56.0, 1),
        MDSYS.SDO_DIM_ELEMENT('M', 0, 300, 1)
    ),
    8307
);

--1F
CREATE INDEX s6_lrs_idx ON S6_LRS(GEOM) INDEXTYPE IS MDSYS.SPATIAL_INDEX;

--2A
SELECT SDO_LRS.VALID_MEASURE(GEOM, 500) AS VALID_500
FROM S6_LRS;

--2B
SELECT SDO_LRS.GEOM_SEGMENT_END_PT(GEOM) AS END_PT
FROM S6_LRS;

--2C
SELECT SDO_LRS.LOCATE_PT(GEOM, 150) AS KM150
FROM S6_LRS;

--2D
SELECT SDO_LRS.CLIP_GEOM_SEGMENT(GEOM, 120, 160) AS CLIPPED
FROM S6_LRS;

--2E
SELECT SDO_LRS.PROJECT_PT(s.GEOM, c.GEOM) AS "WJAZD NA S6"
FROM S6_LRS s, MAJOR_CITIES c
WHERE c.CITY_NAME = 'Slupsk';

--2F
SELECT SDO_GEOM.SDO_LENGTH(
    SDO_LRS.OFFSET_GEOM_SEGMENT(GEOM, 50, 200, 50, 1, 'unit=m'),
    1,
    'unit=km'
) * 1 AS KOSZT
FROM S6_LRS;