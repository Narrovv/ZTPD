
-- 1A
SELECT LPAD('-', 2 * (LEVEL - 1), '-') || t.owner || '.' || t.type_name || 
       '(FINAL:' || t.final || ', INSTANTIABLE:' || t.instantiable || 
       ', ATTRIBUTES:' || t.attributes || ', METHODS:' || t.methods || ')' AS HIERARCHIA
FROM ALL_TYPES t
START WITH t.type_name = 'ST_GEOMETRY'
CONNECT BY PRIOR t.type_name = t.supertype_name
       AND PRIOR t.owner = t.owner;

-- 1B
SELECT DISTINCT m.method_name
FROM ALL_TYPE_METHODS m
WHERE m.type_name LIKE 'ST_POLYGON'
  AND m.owner = 'MDSYS'
ORDER BY 1;

-- 1C
CREATE TABLE MYST_MAJOR_CITIES (
    FIPS_CNTRY VARCHAR2(2),
    CITY_NAME VARCHAR2(40),
    STGEOM ST_POINT
);

-- 1D
INSERT INTO MYST_MAJOR_CITIES
SELECT FIPS_CNTRY, CITY_NAME, TREAT(ST_POINT.FROM_SDO_GEOM(GEOM) AS ST_POINT)
FROM MAJOR_CITIES;

