-- 2A
SELECT c.CITY_NAME AS MIASTO, SDO_NN_DISTANCE(1) AS ODL
FROM MAJOR_CITIES c, MAJOR_CITIES w
WHERE w.CITY_NAME = 'Warsaw'
  AND c.CITY_NAME <> 'Warsaw'
  AND SDO_NN(c.GEOM, w.GEOM, 'sdo_num_res=10 unit=km', 1) = 'TRUE'
  AND ROWNUM <= 9;

-- 2B
SELECT c.CITY_NAME AS MIASTO
FROM MAJOR_CITIES c, MAJOR_CITIES w
WHERE w.CITY_NAME = 'Warsaw'
  AND c.CITY_NAME <> 'Warsaw'
  AND SDO_WITHIN_DISTANCE(c.GEOM, w.GEOM, 'distance=100 unit=km') = 'TRUE';

-- 2C
SELECT b.CNTRY_NAME AS KRAJ, c.CITY_NAME AS MIASTO
FROM COUNTRY_BOUNDARIES b, MAJOR_CITIES c
WHERE b.CNTRY_NAME = 'Slovakia'
  AND SDO_RELATE(c.GEOM, b.GEOM, 'mask=INSIDE') = 'TRUE';

-- 2D
SELECT b.CNTRY_NAME AS PANSTWO, SDO_GEOM.SDO_DISTANCE(b.GEOM, p.GEOM, 1, 'unit=km') AS ODL
FROM COUNTRY_BOUNDARIES b, COUNTRY_BOUNDARIES p
WHERE p.CNTRY_NAME = 'Poland'
  AND b.CNTRY_NAME <> 'Poland'
  AND SDO_RELATE(b.GEOM, p.GEOM, 'mask=TOUCH') <> 'TRUE'
  AND SDO_GEOM.SDO_DISTANCE(b.GEOM, p.GEOM, 1, 'unit=km') > 0;

-- 3A
SELECT b.CNTRY_NAME, SDO_GEOM.SDO_LENGTH(SDO_GEOM.SDO_INTERSECTION(b.GEOM, p.GEOM, 1), 1, 'unit=km') AS ODLEGLOSC
FROM COUNTRY_BOUNDARIES b, COUNTRY_BOUNDARIES p
WHERE p.CNTRY_NAME = 'Poland'
  AND SDO_RELATE(b.GEOM, p.GEOM, 'mask=TOUCH') = 'TRUE';

-- 3B
SELECT CNTRY_NAME
FROM (
    SELECT CNTRY_NAME, SDO_GEOM.SDO_AREA(GEOM, 1, 'unit=sq_km') AS AREA
    FROM COUNTRY_BOUNDARIES
    ORDER BY AREA DESC
)
WHERE ROWNUM = 1;

-- 3C
SELECT SDO_GEOM.SDO_AREA(
    SDO_GEOM.SDO_MBR(
        SDO_GEOM.SDO_UNION(w.GEOM, l.GEOM, 1)
    ),
    1,
    'unit=sq_km'
) AS SQ_KM
FROM MAJOR_CITIES w, MAJOR_CITIES l
WHERE w.CITY_NAME = 'Warsaw'
  AND l.CITY_NAME = 'Lodz';

-- 3D
SELECT SDO_GEOM.SDO_UNION(p.GEOM, c.GEOM, 1).SDO_GTYPE AS GTYPE
FROM COUNTRY_BOUNDARIES p, MAJOR_CITIES c
WHERE p.CNTRY_NAME = 'Poland'
  AND c.CITY_NAME = 'Prague';

-- 3E
SELECT c.CITY_NAME, b.CNTRY_NAME
FROM MAJOR_CITIES c, COUNTRY_BOUNDARIES b
WHERE c.CNTRY_NAME = b.CNTRY_NAME
ORDER BY SDO_GEOM.SDO_DISTANCE(c.GEOM, SDO_GEOM.SDO_CENTROID(b.GEOM, 1), 1) ASC
FETCH FIRST 1 ROWS ONLY;

-- 3F
SELECT 
    r.NAME, 
    ROUND(SUM(SDO_GEOM.SDO_LENGTH(SDO_GEOM.SDO_INTERSECTION(r.GEOM, p.GEOM, 1), 1, 'unit=km')), 7) AS DLUGOSC
FROM RIVERS r, COUNTRY_BOUNDARIES p
WHERE p.CNTRY_NAME = 'Poland'
  AND SDO_RELATE(r.GEOM, p.GEOM, 'mask=ANYINTERACT') = 'TRUE'
GROUP BY r.NAME;